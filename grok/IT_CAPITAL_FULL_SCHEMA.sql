-- -----------------------------------------------------------------------------
-- 16. USER_TOKEN  (Personal/SCV session pattern — single active JWT per user)
-- -----------------------------------------------------------------------------
CREATE TABLE USER_TOKEN (
    REF_NO            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERID            VARCHAR2(60) NOT NULL,   -- PF / encrypted id as in Personal
    USERNAME          NVARCHAR2(150),
    LASTTOKEN         NVARCHAR2(800),
    HASH_TOKEN        NVARCHAR2(200),
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_USER_TOKEN_USERID ON USER_TOKEN (USERID);

-- -----------------------------------------------------------------------------
-- 17. LOGIN_CAPTCHA_QUESTION
--     Personal uses SQL Server login_question; we keep captcha in our Oracle app DB
--     so login works the same way (question + answer) without depending on SCV tables.
-- -----------------------------------------------------------------------------
CREATE TABLE LOGIN_CAPTCHA_QUESTION (
    Q_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QUESTION_TEXT     VARCHAR2(500) NOT NULL,
    ANSWER_TEXT       VARCHAR2(200) NOT NULL,
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CK_CAPTCHA_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

