-- ALTER USER IT_CAPITAL QUOTA UNLIMITED ON USERS;

ALTER SESSION SET CURRENT_SCHEMA = IT_CAPITAL;

-- -----------------------------------------------------------------------------
-- 1. DEPARTMENT
-- -----------------------------------------------------------------------------
CREATE TABLE DEPARTMENT (
    DEPT_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEPT_CODE         VARCHAR2(50),
    DEPT_NAME         VARCHAR2(200) NOT NULL,
    HAS_REVENUE       CHAR(1) DEFAULT 'N' NOT NULL,  -- 'Y' only for DIT (client)
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT CK_DEPT_HAS_REV CHECK (HAS_REVENUE IN ('Y','N')),
    CONSTRAINT CK_DEPT_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE UNIQUE INDEX UK_DEPT_NAME ON DEPARTMENT (DEPT_NAME);

-- -----------------------------------------------------------------------------
-- 2. SECTION  (belongs to department)
-- -----------------------------------------------------------------------------
CREATE TABLE SECTION (
    SECTION_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEPT_ID           NUMBER NOT NULL,
    SECTION_CODE      VARCHAR2(50),
    SECTION_NAME      VARCHAR2(300) NOT NULL,
    DESCRIPTION       VARCHAR2(500),
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT FK_SECTION_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT (DEPT_ID),
    CONSTRAINT CK_SECTION_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE INDEX IX_SECTION_DEPT ON SECTION (DEPT_ID);
CREATE UNIQUE INDEX UK_SECTION_DEPT_NAME ON SECTION (DEPT_ID, SECTION_NAME);

-- -----------------------------------------------------------------------------
-- 3. SECTION_AUTHORITY  (manager: CM, AGM, DGM, GM, CGM — PF + name)
--     One CM can map to many sections (many rows with same CM PF)
-- -----------------------------------------------------------------------------
CREATE TABLE SECTION_AUTHORITY (
    AUTHORITY_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SECTION_ID        NUMBER NOT NULL,
    AUTHORITY_ROLE    VARCHAR2(20) NOT NULL,  -- CM / AGM / DGM / GM / CGM
    PF_NO             VARCHAR2(20) NOT NULL,
    PERSON_NAME       VARCHAR2(200),
    DESIGNATION       VARCHAR2(100),
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT FK_AUTH_SECTION FOREIGN KEY (SECTION_ID) REFERENCES SECTION (SECTION_ID),
    CONSTRAINT CK_AUTH_ROLE CHECK (AUTHORITY_ROLE IN ('CM','AGM','DGM','GM','CGM')),
    CONSTRAINT CK_AUTH_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
    CONSTRAINT UK_AUTH_SECTION_ROLE UNIQUE (SECTION_ID, AUTHORITY_ROLE)
);

CREATE INDEX IX_AUTH_PF ON SECTION_AUTHORITY (PF_NO);

-- -----------------------------------------------------------------------------
-- 4. SECTION_TEAM_MEMBER  (manager: team under section, PF-wise, soft delete)
-- -----------------------------------------------------------------------------
CREATE TABLE SECTION_TEAM_MEMBER (
    MEMBER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SECTION_ID        NUMBER NOT NULL,
    PF_NO             VARCHAR2(20) NOT NULL,
    PERSON_NAME       VARCHAR2(200),
    DESIGNATION       VARCHAR2(100),
    MEMBER_ROLE       VARCHAR2(100),          -- free text role if needed
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT FK_MEMBER_SECTION FOREIGN KEY (SECTION_ID) REFERENCES SECTION (SECTION_ID),
    CONSTRAINT CK_MEMBER_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
    CONSTRAINT UK_MEMBER_SECTION_PF UNIQUE (SECTION_ID, PF_NO)
);

CREATE INDEX IX_MEMBER_PF ON SECTION_TEAM_MEMBER (PF_NO);

-- -----------------------------------------------------------------------------
-- 5. PROJECT  (Capital only — under section)
-- -----------------------------------------------------------------------------
CREATE TABLE PROJECT (
    PROJECT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SECTION_ID        NUMBER NOT NULL,
    PROJECT_CODE      VARCHAR2(50),           -- e.g. 10.2 from master sheet
    PROJECT_NAME      VARCHAR2(500) NOT NULL,
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT FK_PROJECT_SECTION FOREIGN KEY (SECTION_ID) REFERENCES SECTION (SECTION_ID),
    CONSTRAINT CK_PROJECT_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE INDEX IX_PROJECT_SECTION ON PROJECT (SECTION_ID);
CREATE UNIQUE INDEX UK_PROJECT_SECTION_NAME ON PROJECT (SECTION_ID, PROJECT_NAME);

-- -----------------------------------------------------------------------------
-- 6. PROJECT_FY_ALLOTMENT  (Capital master — per FY)
--     Source of truth: SPILLOVER_ALLOTTED + FRESH_ALLOTTED (from presentation/client)
--     TOTAL_ALLOTTED = spillover + fresh — calculated by app when saving (NOT user-typed)
--     We do NOT assume client enters Total first — that was never confirmed
-- -----------------------------------------------------------------------------
CREATE TABLE PROJECT_FY_ALLOTMENT (
    ALLOTMENT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID           NUMBER NOT NULL,
    FINANCIAL_YEAR       VARCHAR2(20) NOT NULL,   -- e.g. 2025-26
    SPILLOVER_ALLOTTED   NUMBER(20,2) DEFAULT 0 NOT NULL,
    FRESH_ALLOTTED       NUMBER(20,2) DEFAULT 0 NOT NULL,
    TOTAL_ALLOTTED       NUMBER(20,2) DEFAULT 0 NOT NULL,  -- app-calculated only
    IS_ACTIVE            CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP,
    CREATED_BY           VARCHAR2(100),
    UPDATED_BY           VARCHAR2(100),
    CONSTRAINT FK_PALL_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (PROJECT_ID),
    CONSTRAINT CK_PALL_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
    CONSTRAINT UK_PALL_PROJ_FY UNIQUE (PROJECT_ID, FINANCIAL_YEAR)
);

-- -----------------------------------------------------------------------------
-- 7. CAPITAL_MONTHLY_ENTRY  (user monthly Capital submit)
--     Previous-month / cumulative figures are NOT stored — computed from older rows
--     ACTUAL_TOTAL / EST_TOTAL_NEXT = app-calculated (spillover+fresh), not typed
--     JUSTIFICATION_TEXT = ONE column (BRD sample + client: one field on page)
--     Annexure-B lists what to write inside that text (approvals + PO/vendor) — not 2 DB columns
-- -----------------------------------------------------------------------------
CREATE TABLE CAPITAL_MONTHLY_ENTRY (
    ENTRY_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID              NUMBER NOT NULL,
    FINANCIAL_YEAR          VARCHAR2(20) NOT NULL,
    ENTRY_MONTH             VARCHAR2(20) NOT NULL,  -- April, May, ... March
    ACTUAL_SPILLOVER        NUMBER(20,2) DEFAULT 0 NOT NULL,
    ACTUAL_FRESH            NUMBER(20,2) DEFAULT 0 NOT NULL,
    ACTUAL_TOTAL            NUMBER(20,2) DEFAULT 0 NOT NULL,  -- app-calculated
    EST_SPILLOVER_NEXT      NUMBER(20,2) DEFAULT 0 NOT NULL,
    EST_FRESH_NEXT          NUMBER(20,2) DEFAULT 0 NOT NULL,
    EST_TOTAL_NEXT          NUMBER(20,2) DEFAULT 0 NOT NULL,  -- app-calculated
    JUSTIFICATION_TEXT      VARCHAR2(4000),  -- one field: PO / approvals / vendor notes
    SUBMITTED_AT            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    SUBMITTED_BY            VARCHAR2(100),
    IS_ACTIVE               CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP,
    CREATED_BY              VARCHAR2(100),
    UPDATED_BY              VARCHAR2(100),
    CONSTRAINT FK_CAP_ENTRY_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (PROJECT_ID),
    CONSTRAINT CK_CAP_ENTRY_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
    CONSTRAINT CK_CAP_ENTRY_MONTH CHECK (ENTRY_MONTH IN (
        'April','May','June','July','August','September',
        'October','November','December','January','February','March')),
    CONSTRAINT UK_CAP_ENTRY UNIQUE (PROJECT_ID, FINANCIAL_YEAR, ENTRY_MONTH)
);

CREATE INDEX IX_CAP_ENTRY_FY_MON ON CAPITAL_MONTHLY_ENTRY (FINANCIAL_YEAR, ENTRY_MONTH);

