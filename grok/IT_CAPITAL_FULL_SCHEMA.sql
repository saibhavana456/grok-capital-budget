-- -----------------------------------------------------------------------------
-- 11. REVENUE_MONTHLY_ENTRY_LINE  (one amount per expenditure head)
-- -----------------------------------------------------------------------------
CREATE TABLE REVENUE_MONTHLY_ENTRY_LINE (
    LINE_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTRY_ID          NUMBER NOT NULL,
    HEAD_ID           NUMBER NOT NULL,
    AMOUNT            NUMBER(20,2) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_REV_LINE_ENTRY FOREIGN KEY (ENTRY_ID) REFERENCES REVENUE_MONTHLY_ENTRY (ENTRY_ID),
    CONSTRAINT FK_REV_LINE_HEAD FOREIGN KEY (HEAD_ID) REFERENCES REVENUE_HEAD (HEAD_ID),
    CONSTRAINT UK_REV_LINE UNIQUE (ENTRY_ID, HEAD_ID)
);

CREATE INDEX IX_REV_LINE_HEAD ON REVENUE_MONTHLY_ENTRY_LINE (HEAD_ID);

-- -----------------------------------------------------------------------------
-- 12. APP_USER  (login / roles — AD mapping later via AD_LOGIN_ID)
--     Roles: ADMIN (masters till CM), CM, MEMBER
-- -----------------------------------------------------------------------------
CREATE TABLE APP_USER (
    USER_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PF_NO             VARCHAR2(20) NOT NULL,
    USER_NAME         VARCHAR2(200),
    DESIGNATION       VARCHAR2(100),
    ROLE_CODE         VARCHAR2(20) NOT NULL,  -- ADMIN / CM / MEMBER
    AD_LOGIN_ID       VARCHAR2(200),          -- for AD login later (SRS)
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT UK_USER_PF UNIQUE (PF_NO),
    CONSTRAINT CK_USER_ROLE CHECK (ROLE_CODE IN ('ADMIN','CM','MEMBER')),
    CONSTRAINT CK_USER_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

-- -----------------------------------------------------------------------------
-- 13. USER_SECTION_MAP  (which sections a user can access — CM multi-section)
-- -----------------------------------------------------------------------------
CREATE TABLE USER_SECTION_MAP (
    MAP_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID           NUMBER NOT NULL,
    SECTION_ID        NUMBER NOT NULL,
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT FK_USM_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_USM_SECTION FOREIGN KEY (SECTION_ID) REFERENCES SECTION (SECTION_ID),
    CONSTRAINT CK_USM_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
    CONSTRAINT UK_USM UNIQUE (USER_ID, SECTION_ID)
);

