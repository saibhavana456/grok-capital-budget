-- -----------------------------------------------------------------------------
-- 14. APP_USER
--     Production login (Personal/SCV pattern + your confirm):
--       PF (user_id) + AD password + captcha → AD validateDomainUser → JWT
--     Staff name/dept from SQL Server STAFF_DETAILS (not stored as employee master here).
--     One person → one department (new convo).
-- -----------------------------------------------------------------------------
CREATE TABLE APP_USER (
    USER_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PF_NO             VARCHAR2(20) NOT NULL,   -- same as AD user_id / EMP_ID
    USER_NAME         VARCHAR2(200),
    DESIGNATION       VARCHAR2(100),
    DEPT_ID           NUMBER,                  -- auto dept; one person one dept
    ROLE_CODE         VARCHAR2(20) NOT NULL,  -- ADMIN / CM / MEMBER
    AD_LOGIN_ID       VARCHAR2(200),          -- AD login id if different from PF
    IS_ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CREATED_BY        VARCHAR2(100),
    UPDATED_BY        VARCHAR2(100),
    CONSTRAINT UK_USER_PF UNIQUE (PF_NO),
    CONSTRAINT FK_USER_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT (DEPT_ID),
    CONSTRAINT CK_USER_ROLE CHECK (ROLE_CODE IN ('ADMIN','CM','MEMBER')),
    CONSTRAINT CK_USER_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

-- -----------------------------------------------------------------------------
