-- =============================================================================
-- IT CAPITAL & REVENUE BUDGET MONITORING — FULL ORACLE SCHEMA
-- Schema/user name: IT_CAPITAL
-- Amounts: Rs. in Crore → NUMBER(20,2)
-- Month: name (April, May, ... March) — Indian FY Apr–Mar
-- Soft delete: IS_ACTIVE 'Y'/'N' (no hard delete for masters)
-- Run as a user that can CREATE USER / or create objects inside IT_CAPITAL
-- =============================================================================

