-- =============================================================================
-- FIX: Checker 600221 sees 0 Capital / Revenue pending (and 0 submissions)
-- Run in SQL Developer connected as the app Oracle user. SET DEFINE OFF first.
-- =============================================================================
-- Root causes this script addresses:
--   1) DEPARTMENT.CHECKER_PF / PROJECT.CHECKER_PF / SECTION.CHECKER_PF not 600221
--   2) APP_USER missing or inactive for 600221
--   3) No PENDING July (or current) capital/revenue rows
--   4) Soft-deleted departments / projects
-- =============================================================================

SET DEFINE OFF;

-- ---------- 1) DIAGNOSE (read-only) ----------
SELECT 'DEPT' AS SRC, DEPT_CODE, MAKER_PF, CHECKER_PF, IS_ACTIVE
FROM DEPARTMENT
ORDER BY DEPT_ID;

SELECT 'APP_USER' AS SRC, PF_NO, ROLE_CODE, DEPT_ID, IS_ACTIVE
FROM APP_USER
WHERE PF_NO IN ('600110','600221','600222','100001');

SELECT e.ENTRY_ID, e.ENTRY_MONTH, e.ENTRY_STATUS, e.SUBMITTED_BY_PF,
       p.PROJECT_NAME, p.CHECKER_PF AS PROJECT_CHECKER, d.CHECKER_PF AS DEPT_CHECKER, d.IS_ACTIVE AS DEPT_ACTIVE
FROM CAPITAL_MONTHLY_ENTRY e
JOIN PROJECT p ON p.PROJECT_ID = e.PROJECT_ID
JOIN SECTION s ON s.SECTION_ID = p.SECTION_ID
JOIN DEPARTMENT d ON d.DEPT_ID = s.DEPT_ID
WHERE e.IS_ACTIVE = 'Y'
ORDER BY e.SUBMITTED_AT DESC NULLS LAST;

SELECT e.ENTRY_ID, e.ENTRY_MONTH, e.ENTRY_STATUS, e.SUBMITTED_BY_PF,
       s.SECTION_NAME, s.CHECKER_PF AS SECTION_CHECKER, d.CHECKER_PF AS DEPT_CHECKER
FROM REVENUE_MONTHLY_ENTRY e
JOIN SECTION s ON s.SECTION_ID = e.SECTION_ID
JOIN DEPARTMENT d ON d.DEPT_ID = s.DEPT_ID
WHERE e.IS_ACTIVE = 'Y'
ORDER BY e.SUBMITTED_AT DESC NULLS LAST;

-- ---------- 2) ENSURE CHECKER USER ----------
MERGE INTO APP_USER u
USING (
  SELECT '600221' AS PF_NO,
         'SAMPLE Checker' AS USER_NAME,
         'Checker' AS DESIGNATION,
         (SELECT DEPT_ID FROM DEPARTMENT WHERE DEPT_CODE = 'DIT' AND IS_ACTIVE = 'Y' AND ROWNUM = 1) AS DEPT_ID,
         'CHECKER' AS ROLE_CODE,
         '600221' AS AD_LOGIN_ID
  FROM DUAL
) src
ON (u.PF_NO = src.PF_NO)
WHEN MATCHED THEN UPDATE SET
  u.IS_ACTIVE = 'Y',
  u.ROLE_CODE = 'CHECKER',
  u.DEPT_ID = NVL(src.DEPT_ID, u.DEPT_ID),
  u.UPDATED_AT = SYSTIMESTAMP,
  u.UPDATED_BY = 'FIX_SCRIPT'
WHEN NOT MATCHED THEN INSERT (PF_NO, USER_NAME, DESIGNATION, DEPT_ID, ROLE_CODE, AD_LOGIN_ID, IS_ACTIVE, CREATED_BY)
VALUES (src.PF_NO, src.USER_NAME, src.DESIGNATION, src.DEPT_ID, src.ROLE_CODE, src.AD_LOGIN_ID, 'Y', 'FIX_SCRIPT');

-- Maker (needed for submissions)
MERGE INTO APP_USER u
USING (
  SELECT '600110' AS PF_NO,
         'SAMPLE Maker' AS USER_NAME,
         'Maker' AS DESIGNATION,
         (SELECT DEPT_ID FROM DEPARTMENT WHERE DEPT_CODE = 'DIT' AND IS_ACTIVE = 'Y' AND ROWNUM = 1) AS DEPT_ID,
         'MAKER' AS ROLE_CODE,
         '600110' AS AD_LOGIN_ID
  FROM DUAL
) src
ON (u.PF_NO = src.PF_NO)
WHEN MATCHED THEN UPDATE SET u.IS_ACTIVE = 'Y', u.ROLE_CODE = 'MAKER', u.UPDATED_BY = 'FIX_SCRIPT'
WHEN NOT MATCHED THEN INSERT (PF_NO, USER_NAME, DESIGNATION, DEPT_ID, ROLE_CODE, AD_LOGIN_ID, IS_ACTIVE, CREATED_BY)
VALUES (src.PF_NO, src.USER_NAME, src.DESIGNATION, src.DEPT_ID, src.ROLE_CODE, src.AD_LOGIN_ID, 'Y', 'FIX_SCRIPT');

-- ---------- 3) POINT DIT CHECKER TO 600221 ----------
UPDATE DEPARTMENT
SET CHECKER_PF = '600221',
    MAKER_PF = NVL(MAKER_PF, '600110'),
    IS_ACTIVE = 'Y',
    UPDATED_AT = SYSTIMESTAMP,
    UPDATED_BY = 'FIX_SCRIPT'
WHERE DEPT_CODE = 'DIT';

-- If ALTER_PROJECT_SECTION_MAKER_CHECKER.sql was run, also set project/section
BEGIN
  EXECUTE IMMEDIATE q'[
    UPDATE PROJECT p
    SET CHECKER_PF = ''600221'',
        MAKER_PF = NVL(MAKER_PF, ''600110''),
        UPDATED_AT = SYSTIMESTAMP,
        UPDATED_BY = ''FIX_SCRIPT''
    WHERE EXISTS (
      SELECT 1 FROM SECTION s
      JOIN DEPARTMENT d ON d.DEPT_ID = s.DEPT_ID
      WHERE s.SECTION_ID = p.SECTION_ID AND d.DEPT_CODE = ''DIT''
    )
  ]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -904 THEN NULL; -- column not yet added
    ELSE RAISE;
    END IF;
END;
