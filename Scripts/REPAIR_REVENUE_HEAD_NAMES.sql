-- Fix corrupted REVENUE_HEAD names caused by SQL Developer & substitution
-- (PRINTING & STATIONERY became PRINTING 1; M&R became M1)
SET DEFINE OFF;
UPDATE REVENUE_HEAD SET HEAD_NAME = 'PRINTING & STATIONERY' WHERE HEAD_CODE = 'PRINTING_STATIONERY';
UPDATE REVENUE_HEAD SET HEAD_NAME = 'M&R' WHERE HEAD_CODE = 'M_R';
COMMIT;
SELECT HEAD_CODE, HEAD_NAME, DISPLAY_ORDER FROM REVENUE_HEAD ORDER BY DISPLAY_ORDER;
