-- =============================================================================
-- ENTRY_MONTH_UNLOCK: Admin enable for months after deadline
-- Deadline for month M = last day of next calendar month (Priyadarshini).
-- Capital unlock → PROJECT_ID set. Revenue unlock → SECTION_ID set.
-- =============================================================================

SET DEFINE OFF;

BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE ENTRY_MONTH_UNLOCK (
      UNLOCK_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      PROJECT_ID     NUMBER NULL,
      SECTION_ID     NUMBER NULL,
      FINANCIAL_YEAR VARCHAR2(20) NOT NULL,
      ENTRY_MONTH    VARCHAR2(20) NOT NULL,
      IS_ENABLED     CHAR(1) DEFAULT 'Y' NOT NULL,
      ENABLED_BY     VARCHAR2(20),
      ENABLED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT     TIMESTAMP
    )
  ]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF; -- table exists
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IX_EMU_PROJECT ON ENTRY_MONTH_UNLOCK (PROJECT_ID, FINANCIAL_YEAR, ENTRY_MONTH)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IX_EMU_SECTION ON ENTRY_MONTH_UNLOCK (SECTION_ID, FINANCIAL_YEAR, ENTRY_MONTH)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMIT;
